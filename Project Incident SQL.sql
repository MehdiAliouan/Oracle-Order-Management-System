--Création de table historique

CREATE TABLE orders_audit (
    audit_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    order_id NUMBER,
    action_type VARCHAR2(30),
    action_date DATE DEFAULT SYSDATE
);

--Création trigger audit

CREATE OR REPLACE TRIGGER trg_orders_audit
AFTER INSERT OR DELETE ON orders
FOR EACH ROW
BEGIN
    IF INSERTING THEN
        INSERT INTO orders_audit(order_id, action_type)
        VALUES (:NEW.order_id, 'INSERT');
    ELSIF DELETING THEN
        INSERT INTO orders_audit(order_id, action_type)
        VALUES (:OLD.order_id, 'DELETE');
    END IF;
END;
