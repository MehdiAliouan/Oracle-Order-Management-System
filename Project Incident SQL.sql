---modification de la procédure pour création de trigger automatique

CREATE OR REPLACE TRIGGER trg_update_stock
BEFORE INSERT ON order_items
FOR EACH ROW
DECLARE
    v_stock NUMBER;
BEGIN
    SELECT stock INTO v_stock
    FROM products
    WHERE product_id = :NEW.product_id
    FOR UPDATE;

    IF v_stock < :NEW.quantity THEN
        RAISE_APPLICATION_ERROR(-20002, 'Stock insuffisant (trigger)');
    END IF;

    UPDATE products
    SET stock = stock - :NEW.quantity
    WHERE product_id = :NEW.product_id;
END;
/

