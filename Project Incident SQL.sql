---Package  PL/SQL(regroupement de la logique metier dans un package)

CREATE OR REPLACE PACKAGE order_pkg AS

    PROCEDURE create_order (
        p_client_id   IN NUMBER,
        p_product_id  IN NUMBER,
        p_quantity    IN NUMBER
    );

    PROCEDURE cancel_order (
        p_order_id IN NUMBER
    );

    FUNCTION get_client_total (
        p_client_id IN NUMBER
    ) RETURN NUMBER;

END order_pkg;
/

---Corps du package
CREATE OR REPLACE PACKAGE BODY order_pkg AS

    PROCEDURE create_order (
        p_client_id   IN NUMBER,
        p_product_id  IN NUMBER,
        p_quantity    IN NUMBER
    ) IS
        v_order_id NUMBER;
    BEGIN

        INSERT INTO orders (client_id)
        VALUES (p_client_id)
        RETURNING order_id INTO v_order_id;

        INSERT INTO order_items (order_id, product_id, quantity)
        VALUES (v_order_id, p_product_id, p_quantity);

        COMMIT;
    END;


    PROCEDURE cancel_order (
        p_order_id IN NUMBER
    ) IS
    BEGIN
        -- Rétablir le stock
        FOR rec IN (
            SELECT product_id, quantity
            FROM order_items
            WHERE order_id = p_order_id
        ) LOOP
            UPDATE products
            SET stock = stock + rec.quantity
            WHERE product_id = rec.product_id;
        END LOOP;

        DELETE FROM order_items WHERE order_id = p_order_id;
        DELETE FROM orders WHERE order_id = p_order_id;

        COMMIT;
    END;


    FUNCTION get_client_total (
        p_client_id IN NUMBER
    ) RETURN NUMBER
    IS
        v_total NUMBER;
    BEGIN
        SELECT NVL(SUM(oi.quantity * p.price),0)
        INTO v_total
        FROM orders o
        JOIN order_items oi ON o.order_id = oi.order_id
        JOIN products p ON oi.product_id = p.product_id
        WHERE o.client_id = p_client_id;

        RETURN v_total;
    END;

END order_pkg;
/

